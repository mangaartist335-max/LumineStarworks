// Generate supabase/seed.sql from the versioned catalogue and archive data.
//
//   npm run db:seed-sql
//
// The output is idempotent (`on conflict do nothing`) and can be applied
// with `supabase db reset` (local stack) or pasted into the SQL editor after
// the migration.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { anime } from "../data/anime";
import { characters } from "../data/characters";
import { companies, people } from "../data/industry";
import { manga } from "../data/manga";
import { news, seedRecommendations, seedReviews } from "../data/community";
import { boards, seedThreads } from "../data/forums";
import { archiveMembers, archiveThreads, archivePostsAsOf } from "../lib/archive";
import { SEASONS, seasonStart } from "../lib/time";

type V = string | number | boolean | null | undefined | string[] | Record<string, unknown>;

function lit(v: V): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${v.replace(/'/g, "''")}'`;
}

const out: string[] = [];
function insert(table: string, cols: string[], rows: V[][], conflict = "on conflict do nothing") {
  if (rows.length === 0) return;
  out.push(`-- ${table}: ${rows.length} rows`);
  for (let i = 0; i < rows.length; i += 200) {
    const chunk = rows.slice(i, i + 200);
    out.push(`insert into public.${table} (${cols.join(", ")}) values\n${chunk.map((r) => `  (${r.map(lit).join(", ")})`).join(",\n")}\n${conflict};`);
  }
}

out.push("-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.");
out.push("begin;");

const franchises = [...new Set(anime.map((a) => a.franchise).filter(Boolean))] as string[];
const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
insert("franchises", ["slug", "name"], franchises.map((f) => [slugify(f), f]));

const seasonRows: V[][] = [];
for (let y = 2005; y <= 2014; y++) for (const s of SEASONS) seasonRows.push([y, s, seasonStart(y, s)]);
insert("seasons", ["year", "season", "starts_at"], seasonRows);

insert(
  "companies",
  ["id", "slug", "name", "kinds", "about", "founded_note", "visible_from", "sources"],
  companies.map((c) => [c.id, c.slug, c.name, c.kinds, c.about, c.foundedNote, c.visibleFrom, c.sources.map((s) => s.cite)]),
);
insert(
  "people",
  ["id", "slug", "name", "native_name", "occupations", "about", "visible_from", "sources"],
  people.map((p) => [p.id, p.slug, p.name, p.nativeName, p.occupations, p.about, p.visibleFrom, p.sources.map((s) => s.cite)]),
);
insert(
  "anime",
  [
    "id", "slug", "title", "title_japanese", "title_romaji", "synonyms", "type", "episodes_planned", "aired_from", "aired_to",
    "release_year", "release_note", "weekly_from", "premiered_season", "premiered_year", "broadcast", "source", "duration", "rating",
    "synopsis", "synopsis_source", "cover_url", "franchise_slug", "visible_from", "provenance", "sources", "archive_notes",
    "page_planned",
  ],
  anime.map((a) => [
    a.id, a.slug, a.title, a.titleJapanese, a.titleRomaji, a.synonyms, a.type, a.episodesPlanned, a.airedFrom, a.airedTo,
    a.year, a.releaseNote, a.weeklyFrom, a.premiered?.season, a.premiered?.year, a.broadcast, a.source, a.duration, a.rating,
    a.synopsis, a.synopsisSource, a.cover, a.franchise ? slugify(a.franchise) : null, a.visibleFrom, a.provenance,
    a.sources.map((s) => s.cite), a.archiveNotes ?? [], Boolean(a.pagePlanned),
  ]),
);

const genreRows = new Map<string, string>();
for (const a of anime) {
  a.genres.forEach((g) => genreRows.set(g, "genre"));
  a.themes.forEach((t) => genreRows.set(t, "theme"));
}
insert("genres", ["name", "kind"], [...genreRows.entries()].map(([n, k]) => [n, k]));
insert("anime_genres", ["anime_id", "genre"], anime.flatMap((a) => [...a.genres, ...a.themes].map((g) => [a.id, g])));
insert("anime_background", ["anime_id", "position", "body", "visible_from"], anime.flatMap((a) => a.background.map((b, i) => [a.id, i + 1, b.text, b.visibleFrom])));
insert(
  "anime_broadcasts",
  ["anime_id", "position", "label", "at", "note", "visible_from"],
  anime.flatMap((a) => a.broadcasts.map((b, i) => [a.id, i + 1, b.label, b.at, b.note, b.visibleFrom ?? a.visibleFrom])),
);
insert(
  "anime_companies",
  ["anime_id", "company_id", "role", "visible_from"],
  anime.flatMap((a) => [
    ...a.studios.map((c) => [a.id, c, "studio", a.visibleFrom]),
    ...a.producers.map((c) => [a.id, c, "producer", a.visibleFrom]),
    ...a.licensors.map((l) => [a.id, l.companyId, "licensor", l.visibleFrom]),
  ]),
);
insert("episodes", ["anime_id", "number", "title", "aired_at", "note"], anime.flatMap((a) => a.episodeList.map((e) => [a.id, e.number, e.title, e.airedAt, e.note])));
insert(
  "characters",
  ["id", "slug", "name", "native_name", "role", "visible_from", "sources"],
  characters.map((c) => [c.id, c.slug, c.name, c.nativeName, c.role, c.visibleFrom, c.sources.map((s) => s.cite)]),
);
insert("character_facts", ["character_id", "position", "body", "revealed_at"], characters.flatMap((c) => c.bio.map((f, i) => [c.id, i + 1, f.text, f.revealedAt])));
insert(
  "character_relationships",
  ["character_id", "other_id", "label", "revealed_at"],
  characters.flatMap((c) => c.relationships.map((r) => [c.id, r.characterId, r.label, r.revealedAt])),
);
insert("anime_characters", ["anime_id", "character_id", "role", "visible_from"], anime.flatMap((a) => a.characters.map((c) => [a.id, c.characterId, c.role, c.visibleFrom ?? null])));
insert("staff_credits", ["anime_id", "person_id", "role", "note", "visible_from"], anime.flatMap((a) => a.staff.map((s) => [a.id, s.personId, s.role, s.note, s.visibleFrom ?? a.visibleFrom])));
insert("voice_credits", ["anime_id", "character_id", "person_id", "language", "visible_from"], anime.flatMap((a) => a.voices.map((v) => [a.id, v.characterId, v.personId, v.language, v.visibleFrom ?? null])));
insert("theme_songs", ["anime_id", "kind", "title", "artist", "note", "visible_from"], anime.flatMap((a) => a.themesSongs.map((t) => [a.id, t.kind, t.title, t.artist, t.note, t.visibleFrom])));
insert(
  "manga",
  ["id", "slug", "title", "title_japanese", "type", "status", "volumes", "chapters", "published", "serialization", "synopsis", "visible_from", "provenance", "sources"],
  manga.map((m) => [m.id, m.slug, m.title, m.titleJapanese, m.type, m.status, m.volumes, m.chapters, m.published, m.serialization, m.synopsis, m.visibleFrom, m.provenance, m.sources.map((s) => s.cite)]),
);
insert("manga_authors", ["manga_id", "person_id", "role"], manga.flatMap((m) => m.authors.map((a) => [m.id, a.personId, a.role])));
insert(
  "related_entries",
  ["source_type", "source_id", "target_type", "target_id", "kind", "note", "visible_from"],
  [
    ...anime.flatMap((a) => a.relations.map((r) => ["anime", a.id, r.target.type, r.target.id, r.kind, r.note, r.visibleFrom ?? null] as V[])),
    ...manga.flatMap((m) => m.relations.map((r) => ["manga", m.id, r.target.type, r.target.id, r.kind, r.note, r.visibleFrom ?? null] as V[])),
  ],
);
insert("media", ["anime_id", "kind", "url", "caption", "visible_from"], anime.filter((a) => a.cover).map((a) => [a.id, "logo", a.cover, `${a.title} title logo`, a.visibleFrom]));

const threads = archiveThreads();
insert(
  "historical_stat_snapshots",
  ["subject_type", "subject_id", "metric", "value", "captured_at", "source"],
  [
    ...anime.flatMap((a) => a.scores.flatMap((s) => [
      ["anime", String(a.id), "score", s.score, s.capturedAt, s.source.cite],
      ["anime", String(a.id), "scored_by", s.scoredBy, s.capturedAt, s.source.cite],
    ] as V[][])),
    ...threads.filter((t) => t.snapshot && t.postsRecovered !== false).flatMap((t) => [
      ["thread", t.id, "replies", t.snapshot!.replies, t.snapshot!.capturedAt, "YAL archive snapshot"],
      ["thread", t.id, "views", t.snapshot!.views, t.snapshot!.capturedAt, "YAL archive snapshot"],
    ] as V[][]),
  ],
);
insert(
  "news_posts",
  ["id", "slug", "title", "published_at", "author", "body", "provenance", "source"],
  news.map((n) => [n.id, n.slug, n.title, n.publishedAt, n.author, n.body, n.provenance, n.source?.cite]),
);
insert(
  "historical_events",
  ["id", "at", "label", "subject_type", "subject_id", "provenance", "source"],
  [
    ...anime.flatMap((a) =>
      a.broadcasts.filter((b) => b.at).map((b, i) => [`anime-${a.id}-broadcast-${i + 1}`, b.at, `${a.title}: ${b.label}`, "anime", a.id, "documented", a.sources[0]?.cite] as V[]),
    ),
    ...anime.flatMap((a) =>
      a.episodeList.filter((e) => e.airedAt).map((e) => [`anime-${a.id}-ep-${e.number}`, e.airedAt, `${a.title} Episode ${e.number} airs`, "anime", a.id, "documented", a.sources[0]?.cite] as V[]),
    ),
    ...anime.filter((a) => a.visibleFrom).map((a) => [`anime-${a.id}-listed`, a.visibleFrom, `${a.title} added to YAL`, "anime", a.id, "documented", null] as V[]),
  ],
);
insert(
  "archive_members",
  ["name", "avatar", "rank", "joined_at", "joined_label", "moderator", "provenance"],
  archiveMembers().map((m) => [m.name, m.avatar, m.rank, m.joinedAt, m.joinedLabel, m.moderator, m.provenance]),
);
insert("forum_boards", ["slug", "name", "description", "group_name", "position"], boards.map((b, i) => [b.slug, b.name, b.description, b.group, i + 1]));

// Parents before subthreads (parent_thread_id is a foreign key).
const ordered = [...threads].sort((a, b) => Number(Boolean(a.parentThreadId)) - Number(Boolean(b.parentThreadId)));
insert(
  "forum_threads",
  ["id", "board", "title", "author_name", "created_at", "created_tz", "anime_id", "episode", "pinned", "locked", "parent_thread_id", "posts_recovered", "provenance"],
  ordered.map((t) => [t.id, t.board, t.title, t.author, t.createdAt, t.createdTz ?? "JST", t.animeId, t.episode, Boolean(t.pinned), Boolean(t.locked), t.parentThreadId, t.postsRecovered !== false, t.provenance]),
);
insert(
  "forum_thread_snapshots",
  ["thread_id", "captured_at", "replies", "views", "last_reply_at", "last_reply_by", "status", "sidebar"],
  threads.filter((t) => t.snapshot).map((t) => [t.id, t.snapshot!.capturedAt, t.snapshot!.replies, t.snapshot!.views, t.snapshot!.lastReplyAt, t.snapshot!.lastReplyBy, t.snapshot!.status, (t.sidebar ?? {}) as Record<string, unknown>]),
);
const FAR_FUTURE = "9999-12-31T00:00:00Z";
insert(
  "forum_posts",
  ["thread_id", "number", "author_name", "avatar", "author_rank", "author_post_count", "author_online", "body", "posted_at", "posted_tz", "edited_at", "edit_reason", "announcement", "provenance"],
  threads.flatMap((t) =>
    archivePostsAsOf(t.id, FAR_FUTURE).map((p) => [
      t.id, p.number, p.author, p.avatar, p.rank, p.postCount, p.online, p.body, p.at, p.tz, p.editedAt, p.editReason, Boolean(p.announcement),
      p.origin === "reconstructed" ? "reconstructed" : "archived",
    ]),
  ),
);
insert(
  "reviews",
  ["seed_key", "anime_id", "author_name", "posted_at", "episodes_seen", "overall", "story", "animation", "sound", "character", "enjoyment", "body", "helpful", "provenance"],
  seedReviews.map((r) => [r.id, r.animeId, r.author, r.postedAt, r.episodesSeen, r.overall, r.story, r.animation, r.sound, r.character, r.enjoyment, r.body, r.helpful, r.provenance]),
);
insert(
  "recommendations",
  ["seed_key", "from_id", "to_id", "author_name", "reason", "posted_at", "provenance"],
  seedRecommendations.map((r) => [r.id, r.from, r.to, r.author, r.reason, r.postedAt, r.provenance]),
);

out.push("commit;");
const file = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(file, out.join("\n\n") + "\n");
console.log(`Wrote ${file} (${seedThreads.length} reconstructed threads, ${threads.length} threads total)`);
